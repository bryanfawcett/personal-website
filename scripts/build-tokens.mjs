/**
 * Write src/styles/tokens.css from src/brand/tokens.ts.
 *
 * tokens.ts is the single source of the site's design tokens, but it is
 * TypeScript, and the page used to receive its CSS from a function call at
 * render time. That left nothing on disk for a tool that is not TypeScript to
 * read (the Rust verifiers). This writes the same CSS to a real file;
 * BaseLayout inlines that file, so what the tools read is what ships.
 *
 *     pnpm tokens          # regenerate
 *     pnpm tokens --check  # fail if the committed file is stale (CI)
 *
 * The file is generated: edit tokens.ts, never tokens.css.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { tokensToCss } from '../src/brand/tokens.ts';

const OUT = new URL('../src/styles/tokens.css', import.meta.url);
const css =
  '/* GENERATED by scripts/build-tokens.mjs from src/brand/tokens.ts. Do not edit. */\n' +
  tokensToCss() +
  '\n';

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {}
  if (current !== css) {
    console.error('src/styles/tokens.css is stale. Run `pnpm tokens` and commit the result.');
    process.exit(1);
  }
  console.log('tokens.css is up to date');
} else {
  writeFileSync(OUT, css);
  console.log(`wrote src/styles/tokens.css (${css.split('\n').length - 1} lines)`);
}
