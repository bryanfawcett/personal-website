#!/usr/bin/env python3
"""Fail if any stylesheet points at a font file that isn't vendored.

Several of the families are variable fonts where Google serves one file per
subset covering every weight, which makes it easy to generate CSS referencing
filenames that were never downloaded. This catches that in CI rather than as a
silent fallback-font regression in production.

Both stylesheets are read. fonts.css is generated by fetch-fonts.py and carries
the Latin families; global.css carries the hand-written CJK faces built by
build-cjk-subset.mjs. Reading only the generated one reported the vendored Han
subset as unreferenced — a warning that was wrong, and the kind that teaches
people to ignore warnings.
"""

from __future__ import annotations

import pathlib
import re
import sys


def main() -> int:
    root = pathlib.Path(__file__).resolve().parent.parent
    sheets = [root / "src" / "styles" / "fonts.css", root / "src" / "styles" / "global.css"]
    fonts = root / "public" / "fonts"

    referenced: set[str] = set()
    for sheet in sheets:
        referenced |= set(re.findall(r"url\('?/fonts/([^)']+)'?\)", sheet.read_text()))
    on_disk = {f.name for f in fonts.glob("*.woff2")}

    missing = sorted(referenced - on_disk)
    if missing:
        print(f"stylesheets reference files that do not exist: {missing}", file=sys.stderr)
        return 1

    unused = sorted(on_disk - referenced)
    if unused:
        print(f"warning: unreferenced font files: {unused}")

    # Every family here is under the SIL Open Font License, which requires the
    # copyright notice and the licence to travel with the Font Software. The
    # repo shipped 22 font files and no licence at all until this was added;
    # the vendored Han face is a *modified* version, which makes the obligation
    # explicit rather than merely good manners.
    licence = fonts / "OFL.txt"
    if on_disk and not licence.exists():
        print(
            f"{len(on_disk)} vendored fonts but no {licence.name} beside them.\n"
            "The SIL Open Font License requires the notice and licence to ship "
            "with the fonts.",
            file=sys.stderr,
        )
        return 1

    print(f"{len(referenced)} font references all resolve, and OFL.txt ships with them")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
