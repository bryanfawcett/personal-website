//! The site's Rust components, compiled to WebAssembly so an `.astro` page can use one
//! like any other component: real props, a real default slot, no fragment files.
//!
//! One entry point does the work, `render(name, props_json, slot_html)`. The Astro side
//! (`src/integrations/rust`) turns each registered component into an importable Astro
//! component that calls it. Adding a component is a module under `components/` plus one
//! line in [`registry!`]; the typed props for TypeScript come from the same structs.

use std::sync::OnceLock;

use components::site::{Lang, Site};
use maud::PreEscaped;
use serde::Deserialize;
use ts_rs::TS;
use wasm_bindgen::prelude::*;

mod hero;

/// The exported site data is compiled in: a Worker has no filesystem, and the markup must
/// not depend on a fetch. `pnpm site-data` rewrites these; `pnpm rust:wasm:check` fails if
/// the committed module no longer matches them.
static SITE_JSON: &str = include_str!("../../../src/data/generated/site.json");
static UI_JSON: &str = include_str!("../../../src/data/generated/ui.json");

pub(crate) fn site() -> &'static Site {
    static SITE: OnceLock<Site> = OnceLock::new();
    SITE.get_or_init(|| Site::from_json(SITE_JSON, UI_JSON))
}

/// The `lang` prop every localised component takes.
#[derive(Debug, Clone, Copy, Default, Deserialize, TS)]
#[serde(rename_all = "lowercase")]
#[ts(export_to = "lang.ts")]
pub enum LangProp {
    #[default]
    En,
    Zh,
}

impl From<LangProp> for Lang {
    fn from(l: LangProp) -> Lang {
        match l {
            LangProp::En => Lang::En,
            LangProp::Zh => Lang::Zh,
        }
    }
}

/// What a component gets: its parsed props and the default slot, already rendered by Astro.
pub(crate) struct Call<'a> {
    pub props_json: &'a str,
    pub slot: Option<String>,
}

impl Call<'_> {
    pub fn props<'de, T: Deserialize<'de>>(&'de self) -> Result<T, String> {
        serde_json::from_str(self.props_json).map_err(|e| format!("bad props: {e}"))
    }
    /// The slot as trusted markup. `None` when the page passed none: a component may
    /// draw differently for that (the hero omits its actions row).
    pub fn slot(&self) -> Option<PreEscaped<String>> {
        self.slot.clone().map(PreEscaped)
    }
}

/// name -> (render, TypeScript props). One line per component.
macro_rules! registry {
    ($($name:literal => $module:ident),* $(,)?) => {
        fn dispatch(name: &str, call: Call) -> Result<String, String> {
            match name {
                $($name => $module::render(call),)*
                other => Err(format!("no Rust component \"{other}\"")),
            }
        }

        /// The registered names, for the Vite plugin to expose as imports.
        const NAMES: &[&str] = &[$($name),*];

        /// `declare module` blocks (props and the component type) for every component,
        /// the content of `src/integrations/rust/components.d.ts`.
        pub fn typings() -> String {
            let mut out = String::from(
                "// Generated by `pnpm rust:wasm` from the props structs in tools/components-wasm. Do not edit.\n\n",
            );
            out.push_str(&format!("type LangProp = {};\n\n", <LangProp as TS>::inline()));
            $(
                out.push_str(&format!(
                    "declare module 'rust:{name}' {{\n  export type Props = {props};\n  /** Default slot: whatever the page nests inside. */\n  const Component: (props: Props & {{ children?: unknown }}) => unknown;\n  export default Component;\n}}\n\n",
                    name = $name,
                    props = $module::props_type(),
                ));
            )*
            out
        }
    };
}

registry! {
    "hero" => hero,
}

/// Render one component to an HTML string.
///
/// `props_json` is the Astro props object as JSON. `slot_html` is the rendered default
/// slot, or `undefined` when the page passed none.
#[wasm_bindgen]
pub fn render(name: &str, props_json: &str, slot_html: Option<String>) -> Result<String, JsError> {
    dispatch(name, Call { props_json, slot: slot_html }).map_err(|e| JsError::new(&e))
}

/// The component names this module serves.
#[wasm_bindgen]
pub fn names() -> Vec<String> {
    NAMES.iter().map(|s| s.to_string()).collect()
}
